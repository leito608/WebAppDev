/**
 * All 78 cards as one list, keyed by slug.
 */
function gypsy_tarot_get_cards() {
	static $cards = null;
	if ( null !== $cards ) {
		return $cards;
	}

	$cards = array();
	foreach ( gypsy_tarot_major_arcana_data() as $index => $card ) {
		$slug           = sanitize_title( $card['name'] );
		$cards[ $slug ] = array_merge(
			$card,
			array(
				'slug'  => $slug,
				'group' => 'major',
				'image' => sprintf( 'major-%02d.jpeg', $index ),
				'title' => $card['name'] . ' (' . $card['th'] . ')',
				'num'   => $index,
			)
		);
	}

	$ranks = gypsy_tarot_rank_data();
	foreach ( gypsy_tarot_suit_data() as $suit_slug => $suit ) {
		foreach ( $ranks as $index => $rank ) {
			$name           = $rank['name'] . ' of ' . $suit['name'];
			$slug           = sanitize_title( $name );
			$court          = $index >= 10;
			$cards[ $slug ] = array(
				'slug'     => $slug,
				'group'    => $suit_slug,
				'image'    => sprintf( '%s-%02d.jpeg', $suit_slug, $index + 1 ),
				'name'     => $name,
				'th'       => $rank['th'] . $suit['th'],
				'title'    => $name . ' (' . $rank['th'] . $suit['th'] . ')',
				'keywords' => $rank['key'] . ' ' . $suit['lens'],
				'intro'    => sprintf(
					'%s ในชุด%s (%s) ซึ่งเกี่ยวกับ%s ไพ่ใบนี้จึงพูดถึง%s %s',
					$rank['name'],
					$suit['th'],
					$suit['element'],
					$suit['domain'],
					$rank['key'],
					$suit['lens']
				),
				'upright'  => $rank['up'] . ' ' . $suit['lens'] . ' ' . ( $court ? 'ไพ่ราชสำนักมักแทนบุคคลหรือบทบาทที่ปรากฏในเรื่องนี้ รวมถึงบุคลิกที่คุณควรนำมาใช้' : 'ให้ดูว่าเรื่องนี้ปรากฏในชีวิตประจำวันของคุณอย่างไร' ),
				'reversed' => $rank['rev'] . ' ' . $suit['lens'] . ' ลองสังเกตว่าอุปสรรคมาจากภายในหรือสถานการณ์ภายนอก',
				'love'     => $rank['love'] . ' โดยเน้น' . $suit['love'],
				'career'   => $rank['career'] . ' โดยเน้น' . $suit['career'],
				'money'    => $rank['money'] . ' โดยเน้น' . $suit['money'],
				'advice'   => 'ถามตัวเองว่า ' . $rank['key'] . $suit['lens'] . 'ปรากฏในชีวิตตอนนี้อย่างไร',
				'num'      => $index + 1,
			);
		}
	}

	return $cards;
}

function gypsy_tarot_card_groups() {
	$groups = array( 'major' => 'ไพ่เมเจอร์อาร์คานา (Major Arcana)' );
	foreach ( gypsy_tarot_suit_data() as $slug => $suit ) {
		$groups[ $slug ] = 'ไพ่ชุด' . $suit['th'] . ' (' . $suit['name'] . ') - ' . $suit['element'];
	}
	return $groups;
}
